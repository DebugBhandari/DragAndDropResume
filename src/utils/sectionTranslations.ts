export function getSectionLabel(locale: LocaleCode, type: SectionType): string {
  const languageKey = LOCALE_TO_LANGUAGE_KEY[locale] ?? 'english';
  const sectionKey = SECTION_TYPE_TO_KEY[type];
  return SECTION_TRANSLATIONS[languageKey][sectionKey] ?? SECTION_TRANSLATIONS.english[sectionKey];
}
